"""
Agent 08 — Email Notification Agent.

Sends the "Your AI Video Recap Is Ready" email via OAuth2:
  * EMAIL_PROVIDER=gmail   -> Gmail API with GMAIL_CLIENT_ID/SECRET/REFRESH_TOKEN
  * EMAIL_PROVIDER=msgraph  -> Microsoft Graph with client-credentials flow

If EMAIL_ENABLED is false or credentials are missing, the agent is a log-only
no-op: it records the intent in EmailRecord and NEVER crashes the pipeline.

No passwords anywhere — OAuth2 tokens only, all from env.
"""
from __future__ import annotations

import base64
import html
import logging
from email.message import EmailMessage

import httpx

from backend.config import Settings, get_settings

log = logging.getLogger("agents.email")


# ---------------------------------------------------------------- template
def recap_ready_template(*, video_title: str, summary: str,
                         download_link: str, recipient_name: str = "") -> tuple[str, str, str]:
    """
    "Your AI Video Recap Is Ready" email.
    Returns (subject, text_body, html_body).
    """
    safe_title = html.escape(video_title or "your video")
    safe_summary = html.escape(summary or "")
    safe_link = html.escape(download_link or "#")
    greeting = f"Hi {html.escape(recipient_name)},<br><br>" if recipient_name else ""
    subject = f"Your AI Video Recap Is Ready: {video_title or 'your video'}"

    text_body = (
        f"Your AI Video Recap Is Ready!\n\n"
        f"Video: {video_title or 'your video'}\n\n"
        f"Summary:\n{summary or '(no summary generated)'}\n\n"
        f"Download your recap video here:\n{download_link}\n\n"
        f"Enjoy!\n— AI Video Recap Platform (100% free, no account needed beyond sign-in)"
    )

    html_body = f"""<!doctype html>
<html><body style="font-family:system-ui,sans-serif;max-width:640px;margin:auto;color:#111">
  <div style="background:#1a2b4a;color:#fff;padding:24px;border-radius:12px 12px 0 0">
    <h1 style="margin:0;font-size:22px">🎬 Your AI Video Recap Is Ready!</h1>
  </div>
  <div style="border:1px solid #e5e7eb;border-top:none;padding:24px;border-radius:0 0 12px 12px">
    <p>{greeting}Your video <strong>{safe_title}</strong> has been processed.</p>
    <h3>Summary</h3>
    <p style="white-space:pre-wrap">{safe_summary or "(no summary generated)"}</p>
    <p><a href="{safe_link}" style="display:inline-block;background:#2563eb;color:#fff;
       padding:12px 24px;border-radius:8px;text-decoration:none;font-weight:600">
       ⬇ Download Recap Video</a></p>
    <p style="color:#6b7280;font-size:13px">This link was generated by the free
       AI Video Recap Platform. If you did not request this, you can ignore it.</p>
  </div>
</body></html>"""
    return subject, text_body, html_body


# ---------------------------------------------------------------- agent
class EmailAgent:
    def __init__(self, settings: Settings | None = None):
        self.settings = settings or get_settings()

    # -- configuration check -------------------------------------------------
    def is_configured(self) -> tuple[bool, str]:
        s = self.settings
        if not s.EMAIL_ENABLED:
            return False, "EMAIL_ENABLED is false"
        if s.EMAIL_PROVIDER == "gmail":
            if s.GMAIL_CLIENT_ID and s.GMAIL_CLIENT_SECRET and s.GMAIL_REFRESH_TOKEN and s.GMAIL_SENDER:
                return True, "gmail"
            return False, "gmail credentials incomplete"
        if s.EMAIL_PROVIDER == "msgraph":
            if s.MSGRAPH_TENANT_ID and s.MSGRAPH_CLIENT_ID and s.MSGRAPH_CLIENT_SECRET and s.MSGRAPH_SENDER:
                return True, "msgraph"
            return False, "msgraph credentials incomplete"
        return False, f"unknown EMAIL_PROVIDER={s.EMAIL_PROVIDER!r}"

    # -- public API ----------------------------------------------------------
    def send_recap_ready(self, *, to_email: str, video_title: str, summary: str,
                         download_link: str, recipient_name: str = "",
                         user_id: str | None = None,
                         job_id: str | None = None) -> dict:
        """
        Send the recap-ready email. Always returns a result dict; on any
        failure records the attempt and returns sent=False — never raises.
        """
        subject, text_body, html_body = recap_ready_template(
            video_title=video_title, summary=summary,
            download_link=download_link, recipient_name=recipient_name)
        result = {"sent": False, "provider": "log", "to": to_email, "subject": subject}
        try:
            ok, reason = self.is_configured()
            if not ok:
                result["note"] = f"email not sent ({reason}); logged only"
                log.info("email log-only to=%s job=%s: %s", to_email, job_id, reason)
            elif self.settings.EMAIL_PROVIDER == "gmail":
                self._send_gmail(to_email, subject, text_body, html_body)
                result.update(sent=True, provider="gmail")
            else:
                self._send_msgraph(to_email, subject, text_body, html_body)
                result.update(sent=True, provider="msgraph")
            log.info("email to=%s job=%s sent=%s provider=%s",
                     to_email, job_id, result["sent"], result["provider"])
        except Exception as exc:  # NEVER crash the pipeline over email
            log.exception("email send failed to=%s job=%s", to_email, job_id)
            result["error"] = str(exc)[:500]
        self._record(user_id=user_id, job_id=job_id, to_email=to_email,
                     subject=subject, provider=result["provider"],
                     sent=result["sent"], error=result.get("error"))
        return result

    # -- Gmail API (OAuth2 refresh-token flow) --------------------------------
    def _gmail_access_token(self) -> str:
        s = self.settings
        resp = httpx.post("https://oauth2.googleapis.com/token", data={
            "client_id": s.GMAIL_CLIENT_ID,
            "client_secret": s.GMAIL_CLIENT_SECRET,
            "refresh_token": s.GMAIL_REFRESH_TOKEN,
            "grant_type": "refresh_token",
        }, timeout=30)
        resp.raise_for_status()
        return resp.json()["access_token"]

    def _send_gmail(self, to_email: str, subject: str, text_body: str, html_body: str) -> None:
        token = self._gmail_access_token()
        msg = EmailMessage()
        msg["From"] = self.settings.GMAIL_SENDER
        msg["To"] = to_email
        msg["Subject"] = subject
        msg.set_content(text_body)
        msg.add_alternative(html_body, subtype="html")
        raw = base64.urlsafe_b64encode(msg.as_bytes()).decode()
        resp = httpx.post(
            "https://gmail.googleapis.com/gmail/v1/users/me/messages/send",
            headers={"Authorization": f"Bearer {token}"},
            json={"raw": raw}, timeout=60)
        resp.raise_for_status()

    # -- Microsoft Graph (client-credentials flow) -----------------------------
    def _msgraph_access_token(self) -> str:
        s = self.settings
        url = (f"https://login.microsoftonline.com/{s.MSGRAPH_TENANT_ID}"
               f"/oauth2/v2.0/token")
        resp = httpx.post(url, data={
            "client_id": s.MSGRAPH_CLIENT_ID,
            "client_secret": s.MSGRAPH_CLIENT_SECRET,
            "scope": "https://graph.microsoft.com/.default",
            "grant_type": "client_credentials",
        }, timeout=30)
        resp.raise_for_status()
        return resp.json()["access_token"]

    def _send_msgraph(self, to_email: str, subject: str, text_body: str, html_body: str) -> None:
        token = self._msgraph_access_token()
        resp = httpx.post(
            f"https://graph.microsoft.com/v1.0/users/{self.settings.MSGRAPH_SENDER}/sendMail",
            headers={"Authorization": f"Bearer {token}"},
            json={"message": {
                "subject": subject,
                "body": {"contentType": "HTML", "content": html_body},
                "toRecipients": [{"emailAddress": {"address": to_email}}],
            }}, timeout=60)
        resp.raise_for_status()

    # -- bookkeeping -----------------------------------------------------------
    def _record(self, *, user_id, job_id, to_email, subject, provider, sent, error=None) -> None:
        try:
            from backend.database import EmailRecord, get_session_factory  # noqa: PLC0415
            db = get_session_factory()()
            try:
                db.add(EmailRecord(user_id=user_id, job_id=job_id, to_email=to_email,
                                   subject=subject, provider=provider, sent=sent,
                                   error=(error or "")[:2000] or None))
                db.commit()
            finally:
                db.close()
        except Exception as exc:
            log.warning("EmailRecord write failed: %s", exc)


__all__ = ["EmailAgent", "recap_ready_template"]
